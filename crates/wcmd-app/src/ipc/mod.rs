//! UI ↔ core IPC: every Tauri command and event, registered in one place. The TS bindings
//! (`packages/bindings`) are generated from this builder.

// Tauri injects command arguments by value, so this pedantic lint is noise for handlers.
#[allow(clippy::needless_pass_by_value)]
pub(crate) mod agents;
#[allow(clippy::needless_pass_by_value)]
pub(crate) mod app;
#[allow(clippy::needless_pass_by_value)]
pub(crate) mod git;
pub(crate) mod pty;
#[allow(clippy::needless_pass_by_value)]
pub(crate) mod settings;
#[allow(clippy::needless_pass_by_value)]
pub(crate) mod state;

use std::path::Path;

use specta_typescript::Typescript;
use tauri_specta::{Builder, collect_commands, collect_events};

/// Where `pnpm gen:bindings` and debug runs write the TS bindings.
pub const BINDINGS_PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../packages/bindings/src/index.ts"
);

/// Every command and event. Keep `build.rs` and `capabilities/main.json` in step.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            app::app_window_ready,
            app::app_set_maximize_button,
            app::app_system_menu,
            app::app_open_link,
            app::app_clipboard_text,
            app::app_pick_folder,
            app::app_pong,
            app::app_about,
            app::app_open_data_folder,
            app::app_quit,
            pty::pty_list_profiles,
            pty::pty_open,
            pty::pty_write,
            pty::pty_resize,
            pty::pty_ack,
            pty::pty_detach,
            state::state_load,
            state::state_save,
            settings::settings_load,
            settings::settings_save,
            agents::agent_list,
            agents::agent_command,
            agents::agent_done,
            git::git_worktrees,
            git::git_worktree_add,
            git::git_worktree_remove,
        ])
        .events(collect_events![
            app::CaptionButtonChanged,
            state::StateHealth,
            agents::AgentActivity,
            agents::ShowPanel,
            app::WindowHidden
        ])
}

/// Writes the bindings to `path`, touching the file only when they changed (a rewrite of an
/// unchanged file would make Vite reload the page).
pub fn export_bindings(builder: &Builder<tauri::Wry>, path: &Path) -> anyhow::Result<()> {
    let staging = path.with_extension("ts.tmp");
    let typescript = Typescript::default().header(
        "// GENERATED by tauri-specta from crates/wcmd-app. Do not edit.\n// Regenerate with `pnpm gen:bindings`.\n",
    );
    builder.export(typescript, &staging)?;
    let fresh = std::fs::read(&staging)?;
    if std::fs::read(path).ok().as_deref() != Some(fresh.as_slice()) {
        std::fs::write(path, &fresh)?;
    }
    std::fs::remove_file(&staging)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn n01_build_rs_and_capabilities_list_every_command() {
        let build = include_str!("../../build.rs");
        let capabilities = include_str!("../../capabilities/main.json");
        let path = std::env::temp_dir().join(format!("wcmd-bindings-{}.ts", std::process::id()));
        export_bindings(&specta_builder(), &path).unwrap();
        let bindings = std::fs::read_to_string(&path).unwrap();
        std::fs::remove_file(&path).unwrap();
        for command in build
            .lines()
            .map(str::trim)
            .filter(|l| l.starts_with('"') && l.ends_with("\","))
            .map(|l| l.trim_matches(|c| c == '"' || c == ','))
        {
            let camel: String = command
                .split('_')
                .enumerate()
                .map(|(i, part)| {
                    if i == 0 {
                        part.to_owned()
                    } else {
                        let mut chars = part.chars();
                        chars.next().map_or_else(String::new, |first| {
                            first.to_uppercase().chain(chars).collect()
                        })
                    }
                })
                .collect();
            assert!(bindings.contains(&format!("\t{camel}: (")), "{command}");
            let permission = format!("\"allow-{}\"", command.replace('_', "-"));
            assert!(capabilities.contains(&permission), "{permission}");
        }
    }

    #[test]
    fn n02_the_installer_ships_the_bundled_console_host() {
        let conf = include_str!("../../tauri.conf.json");
        for file in ["conpty.dll", "OpenConsole.exe"] {
            assert!(
                conf.contains(&format!(
                    "\"../../resources/conpty/x64/{file}\": \"{file}\""
                )),
                "{file}"
            );
        }
    }
}
